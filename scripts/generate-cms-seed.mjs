// Generates the CMS seed migrations (drizzle/0051 + drizzle-pg/0028) from the
// markdown content in web/content. Run after editing seed content:
//   node scripts/generate-cms-seed.mjs
// The migrations are idempotent (INSERT ... ON CONFLICT DO NOTHING) keyed by
// slug, so re-running migrate never duplicates or overwrites admin edits.
import { readFileSync, writeFileSync } from "node:fs";
import { basename } from "node:path";

const POSTS = [
  "web/content/blogs/best-open-source-seo-tools.md",
  "web/content/blogs/dark-queries.md",
  "web/content/blogs/seo-for-startups.md",
];

const LEGAL_PAGES = [
  "web/content/legal/privacy.md",
  "web/content/legal/terms-and-conditions.md",
  "web/content/legal/cookie-policy.md",
  "web/content/legal/refund-policy.md",
  "web/content/legal/dpa.md",
];

function parseFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!match) throw new Error("Missing frontmatter");
  const frontmatter = {};
  for (const line of match[1].split(/\r?\n/)) {
    const kv = line.match(/^(\w+):\s*"?(.*?)"?$/);
    if (kv) frontmatter[kv[1]] = kv[2];
  }
  return { frontmatter, body: match[2].trim() };
}

function slugFromFilename(file) {
  return basename(file).replace(/\.md$/, "");
}

function sqlString(value, dialect) {
  const escaped = value.replace(/'/g, "''");
  return dialect === "pg" ? `$md$${escaped}$md$` : `'${escaped}'`;
}

function buildSql(dialect) {
  const now = new Date().toISOString();
  const statements = [];

  for (const file of POSTS) {
    const raw = readFileSync(file, "utf-8");
    const { frontmatter, body } = parseFrontmatter(raw);
    const slug = slugFromFilename(file);
    const publishedAt = frontmatter.date
      ? new Date(frontmatter.date).toISOString()
      : now;
    statements.push(
      `INSERT INTO cms_posts (id, slug, title, description, content_md, status, published_at, author_user_id, created_at, updated_at) VALUES (${sqlString(`seed-post-${slug}`, dialect)}, ${sqlString(slug, dialect)}, ${sqlString(frontmatter.title, dialect)}, ${sqlString(frontmatter.description ?? "", dialect)}, ${sqlString(body, dialect)}, 'published', ${sqlString(publishedAt, dialect)}, NULL, ${sqlString(now, dialect)}, ${sqlString(now, dialect)}) ON CONFLICT (slug) DO NOTHING;`,
    );
  }

  for (const file of LEGAL_PAGES) {
    const raw = readFileSync(file, "utf-8");
    const { frontmatter, body } = parseFrontmatter(raw);
    const slug = slugFromFilename(file);
    statements.push(
      `INSERT INTO cms_pages (id, slug, title, content_md, status, updated_by_user_id, created_at, updated_at) VALUES (${sqlString(`seed-page-${slug}`, dialect)}, ${sqlString(slug, dialect)}, ${sqlString(frontmatter.title, dialect)}, ${sqlString(body, dialect)}, 'published', NULL, ${sqlString(now, dialect)}, ${sqlString(now, dialect)}) ON CONFLICT (slug) DO NOTHING;`,
    );
  }

  return `-- CMS seed content imported from web/content (generated by scripts/generate-cms-seed.mjs).\n${statements.join("--> statement-breakpoint\n")}\n`;
}

writeFileSync("drizzle/0051_cms_seed.sql", buildSql("sqlite"));
writeFileSync("drizzle-pg/0028_cms_seed.sql", buildSql("pg"));
console.log("Wrote drizzle/0051_cms_seed.sql and drizzle-pg/0028_cms_seed.sql");
